/**
 * Regenerates the whole gallery from gallery/manifest.json.
 *
 * Nothing in gallery/ is hand-edited: the images and the gallery page are both
 * outputs. CI runs this and fails if a single byte moves, which is how the
 * determinism claim stays honest rather than aspirational.
 */

import { writeFileSync, mkdirSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { generate } from '../core/generate';
import { rasterize, downsample } from '../core/render/raster';
import { encodePng } from '../core/render/png';
import { countPaths } from '../core/types';
import { getPalette } from '../core/palette';
import { getPreset, type Preset } from '../core/presets';

/**
 * A manifest entry is just a filename and a preset id. The parameters live in
 * src/presets.json, so the playground's presets and these images are the same
 * definitions rather than two copies that drift.
 */
interface Piece {
  file: string;
  preset: string;
}

interface Manifest {
  /** Target width of the committed PNG, in pixels. */
  thumbWidth: number;
  /** Supersample factor used before downsampling. */
  supersample: number;
  pieces: Piece[];
}

// Resolved from the working directory rather than the bundle, because the
// bundle's depth differs from the source file's and npm always runs scripts
// from the package root.
const galleryDir = join(process.cwd(), 'gallery');
const thumbsDir = join(galleryDir, 'thumbs');

function reproduceCommand(preset: Preset, file: string, ext: string): string {
  const parts = [
    'fieldwork render',
    `--algo ${preset.algo}`,
    `--seed ${preset.seed}`,
    `--palette ${preset.palette}`,
  ];
  for (const [key, value] of Object.entries(preset.params)) {
    parts.push(`--${key} ${value}`);
  }
  parts.push(`--out ${file}.${ext}`);
  return parts.join(' ');
}

function main(): void {
  const manifestPath = join(galleryDir, 'manifest.json');
  if (!existsSync(manifestPath)) {
    throw new Error(
      `No manifest at ${manifestPath}. Run this from the repository root: npm run gallery`,
    );
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as Manifest;

  mkdirSync(thumbsDir, { recursive: true });

  const rows: string[] = [];
  let totalBytes = 0;

  for (const piece of manifest.pieces) {
    const preset = getPreset(piece.preset);
    const started = Date.now();

    const scene = generate({
      algo: preset.algo,
      seed: preset.seed,
      palette: preset.palette,
      params: preset.params,
    });

    // Supersample then box-filter down, so thin strokes survive the shrink.
    const scale = (manifest.thumbWidth / scene.width) * manifest.supersample;
    const png = encodePng(downsample(rasterize(scene, scale), manifest.supersample), {
      Software: 'fieldwork',
      Comment: JSON.stringify(scene.meta),
    });

    const outPath = join(thumbsDir, `${piece.file}.png`);
    writeFileSync(outPath, png);
    totalBytes += png.length;

    console.log(
      `${piece.file}.png  ${countPaths(scene)} paths  ` +
        `${(png.length / 1024).toFixed(0)} KB  ${Date.now() - started}ms`,
    );

    const palette = getPalette(preset.palette);
    rows.push(
      [
        `### ${preset.title}`,
        '',
        `![${preset.title}](thumbs/${piece.file}.png)`,
        '',
        preset.blurb,
        '',
        `**${preset.algo}** · seed \`${preset.seed}\` · palette \`${preset.palette}\` — _${palette.inspiration}_`,
        '',
        `[Open in the playground](https://shell-mp3.github.io/fieldwork/#preset=${preset.id}) · reproduce at full resolution:`,
        '',
        '```bash',
        reproduceCommand(preset, piece.file, 'svg'),
        '```',
        '',
      ].join('\n'),
    );
  }

  const page = [
    '# Gallery',
    '',
    '<!-- Generated by `npm run gallery` from manifest.json. Do not edit by hand. -->',
    '',
    `${manifest.pieces.length} pieces. Each PNG below is committed at ${manifest.thumbWidth}px wide;`,
    'the full-resolution SVG is not committed because it does not need to be — the',
    'command under each piece reproduces it byte for byte.',
    '',
    ...rows,
  ].join('\n');

  writeFileSync(join(galleryDir, 'README.md'), page + '\n', 'utf8');

  console.log(
    `\n${manifest.pieces.length} pieces, ${(totalBytes / 1024 / 1024).toFixed(2)} MB total`,
  );
}

main();
